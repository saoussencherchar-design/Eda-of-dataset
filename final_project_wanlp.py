SHORT_VOWELS = "َُِ"

def text_to_rhythm(text):
    if not isinstance(text, str):
        return ""
    pattern = []
    for ch in text:
        if ch in SHORT_VOWELS:
            pattern.append("◡")
        elif ch in "اوي":
            pattern.append("—")
    return pattern

def rhythm_features(text):
    r = text_to_rhythm(text)
    if len(r) == 0:
        return [0, 0, 0]

    short = r.count("◡")
    long = r.count("—")
    total = short + long + 1e-6

    return [
        short / total,
        long / total,
        len(r)
    ]

