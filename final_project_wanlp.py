import re
from difflib import SequenceMatcher
from collections import Counter

# =========================
#  NORMALIZATION
# =========================
def normalize(text):
    text = re.sub(r'[ًٌٍَُِّْـ]', '', text)
    text = re.sub(r'[إأآا]', 'ا', text)
    text = re.sub(r'ى', 'ي', text)
    text = re.sub(r'ة', 'ه', text)
    text = re.sub(r'[^\u0600-\u06FF\s]', '', text)
    return text.strip()

def tokenize(text):
    return [w for w in normalize(text).split() if len(w) > 1]


# =========================
#  DICTIONARY
# =========================
ANTONYMS = {
    "نور": ["ظلام"], "ظلام": ["نور"],
    "ليل": ["نهار"], "نهار": ["ليل"],
    "شمس": ["قمر"],

    "حياه": ["موت"], "موت": ["حياه"],
    "بقاء": ["فناء"], "فناء": ["بقاء"],

    "حب": ["كره"], "كره": ["حب"],
    "خير": ["شر"], "شر": ["خير"],
    "عدل": ["ظلم"], "ظلم": ["عدل"],
}

QURAN_PHRASES = {
    "بسم الله",
    "الحمد لله",
    "سبحان الله",
    "لا اله الا الله",
    "الله اكبر"
}

NOISE_WORDS = {"هذا", "هذه", "الذي", "التي", "الى", "على", "في", "من", "و"}


# =========================
#  1. JINAS
# =========================
def is_valid_jinas(w1, w2, sim):
    if w1 == w2:
        return False
    if w1 in NOISE_WORDS or w2 in NOISE_WORDS:
        return False
    if len(w1) < 3 or len(w2) < 3:
        return False
    if w1 in w2 or w2 in w1:
        return False
    return 0.78 <= sim < 0.95


def detect_jinas(text):
    words = tokenize(text)
    found = []
    seen = set()

    for i in range(len(words)):
        for j in range(i + 1, len(words)):
            w1, w2 = words[i], words[j]

            sim = SequenceMatcher(None, w1, w2).ratio()
            key = tuple(sorted([w1, w2]))

            if key in seen:
                continue
            seen.add(key)

            if sim >= 0.95:
                found.append({
                    "type": "جناس تام",
                    "w1": w1,
                    "w2": w2,
                    "score": round(sim, 2)
                })

            elif is_valid_jinas(w1, w2, sim):
                found.append({
                    "type": "جناس ناقص",
                    "w1": w1,
                    "w2": w2,
                    "score": round(sim, 2)
                })

    return found


# =========================
#  2. TIBAQ
# =========================
def detect_tibaq(text):
    words = set(tokenize(text))
    found = []

    for k, vals in ANTONYMS.items():
        for v in vals:
            if k in words and v in words:
                found.append({
                    "type": "طباق",
                    "a": k,
                    "b": v
                })

    return found


# =========================
#  3. MUQABALA
# =========================
def detect_muqabala(text):
    tibaq = detect_tibaq(text)

    if len(tibaq) >= 2:
        return [{
            "type": "مقابلة",
            "pairs": tibaq
        }]
    return []


# =========================
#  4. IQTIBAS
# =========================
def detect_iqtibas(text):
    clean = normalize(text)

    return [
        {"type": "اقتباس", "phrase": p}
        for p in QURAN_PHRASES
        if normalize(p) in clean
    ]


# =========================
#  5. SAJ
# =========================
def detect_saj(verses):
    endings = []

    for v in verses:
        words = tokenize(v)
        if words:
            endings.append(words[-1][-2:])

    found = []

    for i in range(len(endings) - 1):
        if endings[i] == endings[i + 1] and endings[i] not in NOISE_WORDS:
            found.append({
                "type": "سجع",
                "pair": (i + 1, i + 2),
                "ending": endings[i]
            })

    return found


# =========================
#  MAIN ANALYZER
# =========================
def analyze_balagha(text):
    verses = [v.strip() for v in text.split("\n") if v.strip()]

    result = {}

    j = detect_jinas(text)
    if j:
        result["الجناس"] = j

    t = detect_tibaq(text)
    if t:
        result["الطباق"] = t

    m = detect_muqabala(text)
    if m:
        result["المقابلة"] = m

    i = detect_iqtibas(text)
    if i:
        result["الاقتباس"] = i

    s = detect_saj(verses)
    if s:
        result["السجع"] = s

    return result


# =========================
#  FUSION
# =========================
def fusion_analysis(text):

    meter, taf, mc = predict_meter(text)
    theme, tc = predict_theme(text)
    qafya = analyze_poem(text)
    bal = analyze_balagha(text)

    return {
        "البحر": meter,
        " التفعيلات": taf,
        " ثقة البحر": round(mc,3),
        " الموضوع": theme,
        " ثقة الموضوع": round(tc,3),
        " القافية": qafya,
        " المحسنات": bal
    }


