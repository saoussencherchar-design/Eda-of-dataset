import re

def clean_arabic(text):
    text = str(text)

    # remove encoding garbage
    text = text.encode("utf-8", errors="ignore").decode("utf-8")

    # keep Arabic only
    text = re.sub(r"[^\u0600-\u06FF\s]", " ", text)

    # clean spaces
    text = re.sub(r"\s+", " ", text)

    return text.strip()

